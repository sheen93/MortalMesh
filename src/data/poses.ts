export function getPosePreset(id: string): PosePreset | undefined {
  return POSE_PRESETS.find((preset) => preset.id === id);
}

export function filterPosePresets(
  query: string,
  category: PoseCategory | 'all'
): PosePreset[] {
  const normalizedQuery = query.trim().toLowerCase();

  return POSE_PRESETS.filter((preset) => {
    if (category !== 'all' && preset.category !== category) {
      return false;
    }
    if (!normalizedQuery) {
      return true;
    }
    const haystack = `${preset.name} ${preset.category} ${preset.tags.join(' ')} ${preset.description}`.toLowerCase();
    return haystack.includes(normalizedQuery);
  });
}
